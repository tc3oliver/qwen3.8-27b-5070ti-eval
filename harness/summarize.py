#!/usr/bin/env python3
"""Collects every model's suite results for one run into results/<run>-summary.{json,md}.
Usage: python3 harness/summarize.py [--run arena-2026-10]"""
import argparse, glob, json, math, os, statistics as st, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser(); ap.add_argument("--run", default="arena-2026-10"); args = ap.parse_args()

def load(p):
    try: return json.load(open(p))
    except Exception: return None

def wilson(k, n, z=1.96):
    if not n: return (None, None)
    p = k / n; d = 1 + z * z / n; c = p + z * z / (2 * n); h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)

def tenq(d):
    rows = {}
    for r in sorted(glob.glob(os.path.join(d, "10q_A_r*.json"))):
        k = r.split("_r")[-1].split(".")[0]; b = os.path.join(d, f"10q_B_r{k}.json")
        if not os.path.exists(b): continue
        out = subprocess.run([sys.executable, os.path.join(ROOT, "harness/grade_10q.py"), r, b,
                              "--out", os.path.join(d, f"10q_grades_r{k}.json")], capture_output=True, text=True)
        g = load(os.path.join(d, f"10q_grades_r{k}.json"))
        toks = sum(v.get("tok") or 0 for f in (r, b) for v in load(f).values())
        rows[k] = {"score": g["total"], "max": g["max"], "tokens": toks}
    return rows

models = {}
for d in sorted(glob.glob(os.path.join(ROOT, "results", "*", args.run))):
    name = d.split(os.sep)[-2]
    if not os.path.exists(os.path.join(d, "humanevalplus.json")) and not os.path.exists(os.path.join(d, "latency.json")):
        continue
    m = {"frozen": (load(os.path.join(d, "frozen.json")) or {}).get("candidate"),
         "spill_end_mib": (load(os.path.join(d, "spill_end.json")) or {}).get("spill_mib_end")}
    he = load(os.path.join(d, "humanevalplus.json"))
    if he:
        s = he["summary"]; lo, hi = wilson(s["pass"], s["n"])
        m["humanevalplus"] = {"pass": s["pass"], "n": s["n"], "pass_at_1": s["pass_at_1"], "ci95": [lo, hi],
                              "median_tok": s["median_tok"], "total_sec": s["total_sec"], "truncated": s["empty_or_truncated"]}
    m["10q"] = tenq(d)
    cr = load(os.path.join(d, "code_review.json"))
    if cr: m["code_review"] = cr["summary"]
    ag = load(os.path.join(d, "agent.json"))
    if ag: m["agent"] = {k: ag["summary"].get(k) for k in ("n", "success", "malformed_calls", "server_errors", "leaked_episodes", "median_turns", "median_wall_sec")}
    lc = load(os.path.join(d, "longctx.json"))
    if lc: m["longctx"] = {str(r["size"]): ({"recalled": r["recalled"], "prefill_tps": r["prefill_tps"], "ttft_s": r["ttft_s"]}
                                            if r.get("status") == "ok" else {"status": r.get("status")}) for r in lc["results"]}
    la = load(os.path.join(d, "latency.json"))
    if la: m["latency"] = la["summary"]
    models[name] = m

json.dump(models, open(os.path.join(ROOT, "results", f"{args.run}-summary.json"), "w"), ensure_ascii=False, indent=1)

def fmt(v, f="{:.1f}"):
    return "—" if v is None else f.format(v)

lines = [f"# {args.run} — summary", "", "Evidence level A (measured here, this protocol). Generated by `harness/summarize.py`.", "",
         "| Model | Setting | HumanEval+ pass@1 (95% CI) | 10Q /40 (tokens) | Code review | Agent | Long ctx recall | 60K prefill tok/s / TTFT s | First answer p50 / p90 s | Total p50 / p90 s | Decode tok/s | Spill end MiB |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for name, m in models.items():
    he = m.get("humanevalplus"); tq = m.get("10q", {}); la = m.get("latency", {}); lc = m.get("longctx", {})
    he_s = f"{he['pass_at_1']*100:.1f}% ({he['ci95'][0]*100:.1f}–{he['ci95'][1]*100:.1f})" if he else "—"
    tq_s = ", ".join(f"{v['score']} ({v['tokens']:,})" for v in tq.values()) or "—"
    cr = m.get("code_review"); cr_s = f"{cr['line_and_cause_ok']}/{cr['n']}" if cr else "—"
    ag = m.get("agent"); ag_s = f"{ag['success']}/{ag['n']}, {ag['malformed_calls']} malformed" if ag else "—"
    lc_s = " · ".join(f"{int(k)//1000}K {v['recalled']}/4" if "recalled" in v else f"{int(k)//1000}K n/a" for k, v in lc.items()) or "—"
    fa = la.get("first_answer_s", {}); tt = la.get("total_s", {})
    lines.append(f"| `{name}` | `{m['frozen']}` | {he_s} | {tq_s} | {cr_s} | {ag_s} | {lc_s} | {fmt((lc.get('60000') or {}).get('prefill_tps'),'{:.0f}')} / {fmt((lc.get('60000') or {}).get('ttft_s'))} | {fmt(fa.get('p50'),'{:.2f}')} / {fmt(fa.get('p90'),'{:.2f}')} | "
                 f"{fmt(tt.get('p50'),'{:.2f}')} / {fmt(tt.get('p90'),'{:.2f}')} | {fmt(la.get('mean_decode_tps'))} | {fmt(m['spill_end_mib'],'{}')} |")
open(os.path.join(ROOT, "results", f"{args.run}-summary.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
